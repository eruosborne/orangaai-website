#!/usr/bin/env python3
"""Rebuild assets/kit.bundle.css from the kit stylesheets.
Run after changing anything in assets/*.css: python3 scripts/bundle-css.py
site.css is NOT in the bundle; pages load it separately so page edits need no rebuild."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
PARTS = [
    "assets/system.css", "assets/ui/cards.css", "assets/motion/motion.css",
    "assets/backgrounds/backgrounds.css", "assets/layout/layout.css", "assets/icons/icon.css",
    "assets/ui/base.css",
    "assets/ui/window/fragment.css", "assets/ui/chat/fragment.css", "assets/ui/notify/fragment.css",
    "assets/ui/checklist/fragment.css", "assets/ui/toggles/fragment.css",
    "assets/ui/integrations/fragment.css", "assets/ui/doc/fragment.css",
]
out = ["/* GENERATED by scripts/bundle-css.py. Do not edit; edit the source files and rerun. */"]
for p in PARTS:
    out.append(f"\n/* ---- {p} ---- */\n" + (ROOT / p).read_text())
(ROOT / "assets/kit.bundle.css").write_text("\n".join(out))
print("wrote assets/kit.bundle.css", sum(len(x) for x in out), "bytes")
